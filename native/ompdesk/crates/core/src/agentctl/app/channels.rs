//! The agent's risk table over every IPC channel (was `app-channels.ts`). A channel is either `never` with the reason,
//! or carries the lowest tier its actions need and the ids of the `ompdesk_app` actions that call it. A channel with
//! no action is denied by default. `app-catalog.test.ts` checks the table against `IPC_POLICY` (through `app.catalog`),
//! so a new channel does not pass until it has an entry here.
//!
//! This is the agent's policy, not `IPC_POLICY`'s: that table says what a paired web device may do.

use super::guard::Tier;

pub enum Risk {
    Never(&'static str),
    Tier(Tier, &'static [&'static str]),
    /// Settings writes ride `PREFS_SET`: its actions are the `settings.<id>` of every row.
    SettingsWrite,
}

