//! ai-memory's wiring of the plain terminal `omp`: what `ai-memory setup --agent omp` writes into omp's agent dir
//! (`extensions/ai-memory-omp.ts` and the `ai-memory` entry of `mcp.json`).
//!
//! OMPdesk never writes it by itself. It exists when the person pressed "Also use in the terminal omp" (OMPdesk then
//! runs ai-memory's own `setup --agent omp`), ran ai-memory's setup in a terminal, or an earlier OMPdesk build wired
//! omp globally (`legacy_owned`). The reverse removes exactly the two things ai-memory adds there: ai-memory has no
//! per-agent uninstall, so this reads them back by their own signatures (the generated file's header, the `ai-memory`
//! MCP entry running an ai-memory binary). The skills `setup` also writes go to the shared `~/.agents/skills` and
//! belong to every agent reading it, so they stay; only those a server-only `setup` newly created are taken back.

use std::collections::BTreeSet;
use std::fs;
use std::path::Path;

use serde_json::{Map, Value};

use super::text::pretty;
use crate::json::whole_surrogates;

/// The files ai-memory's omp installer writes under omp's agent dir.
pub const EXTENSION_FILE: &str = "extensions/ai-memory-omp.ts";
pub const MCP_FILE: &str = "mcp.json";
/// The first line of every extension `install-hooks --agent omp` generates.
pub const GENERATED_HEADER: &str = "// Auto-generated by `ai-memory install-hooks --agent omp";
const SERVER_NAME: &str = "ai-memory";
/// Folder names below `<home>/.agents/skills` that ai-memory manages start with this.
const SKILL_PREFIX: &str = "ai-memory-";

#[derive(Debug, Clone, Default, PartialEq, Eq, serde::Serialize)]
pub struct Wiring {
    pub extension: bool,
    pub mcp: bool,
    /// The MCP entry's command (none without an entry).
    pub command: Option<String>,
}

/// A file's text as `readFile(file, "utf8")` reads it, or none.
pub fn read_text(file: &Path) -> Option<String> {
    fs::read(file)
        .ok()
        .map(|bytes| String::from_utf8_lossy(&bytes).into_owned())
}

/// A JSON file holding an object, or none (missing, not JSON, not an object).
pub fn read_mcp(file: &Path) -> Option<Map<String, Value>> {
    match serde_json::from_str(&whole_surrogates(&read_text(file)?)).ok()? {
        Value::Object(config) => Some(config),
        _ => None,
    }
}

/// `path.basename` of a `/`-separated path: trailing separators dropped, and on Windows a drive's `X:` too.
fn basename(path: &str) -> &str {
    let path = if cfg!(windows)
        && path.len() >= 2
        && path.as_bytes()[1] == b':'
        && path.as_bytes()[0].is_ascii_alphabetic()
    {
        &path[2..]
    } else {
        path
    };
    let trimmed = path.trim_end_matches('/');
    if trimmed.is_empty() {
        return "";
    }
    trimmed.rsplit('/').next().unwrap_or(trimmed)
}

/// Whether `entry` is the stdio or http server ai-memory's `install-mcp` writes.
fn is_ai_memory_entry(entry: Option<&Value>) -> bool {
    let Some(Value::Object(entry)) = entry else {
        return false;
    };
    match (entry.get("command"), entry.get("url")) {
        (Some(Value::String(command)), _) => {
            let name = basename(&command.replace('\\', "/")).to_ascii_lowercase();
            matches!(
                name.as_str(),
                "ai-memory" | "ai-memory.exe" | "ai-memory.cmd"
            )
        }
        (_, Some(Value::String(url))) => url.ends_with("/mcp") || url.ends_with("/mcp/"),
        _ => false,
    }
}

fn generated_extension(file: &Path) -> bool {
    read_text(file).is_some_and(|text| text.starts_with(GENERATED_HEADER))
}

pub fn read_wiring(agent_dir: &Path) -> Wiring {
    let extension = generated_extension(&agent_dir.join(EXTENSION_FILE));
    let config = read_mcp(&agent_dir.join(MCP_FILE));
    let entry = config
        .as_ref()
        .and_then(|config| config.get("mcpServers"))
        .and_then(|servers| servers.get(SERVER_NAME));
    let mcp = is_ai_memory_entry(entry);
    let command = entry
        .and_then(|entry| entry.get("command"))
        .and_then(Value::as_str)
        .filter(|_| mcp)
        .map(str::to_owned);
    Wiring {
        extension,
        mcp,
        command,
    }
}

/// node's `normalizeString`: `.` and `..` parts resolved, repeated separators folded.
fn normalize_parts(
    path: &[char],
    allow_above_root: bool,
    separator: char,
    is_separator: fn(char) -> bool,
) -> String {
    let mut res: Vec<char> = Vec::new();
    let mut last_segment_length: isize = 0;
    let mut last_slash: isize = -1;
    let mut dots: i32 = 0;
    let mut code = '\0';
    let last_separator = |res: &[char]| {
        res.iter()
            .rposition(|c| *c == separator)
            .map_or(-1, |at| at as isize)
    };
    for i in 0..=path.len() {
        if i < path.len() {
            code = path[i];
        } else if is_separator(code) {
            break;
        } else {
            code = '/';
        }
        let at = i as isize;
        if is_separator(code) {
            if last_slash == at - 1 || dots == 1 {
                // A repeated separator or a `.` part adds nothing.
            } else if dots == 2 {
                let ends_in_dots = res.len() >= 2
                    && last_segment_length == 2
                    && res[res.len() - 1] == '.'
                    && res[res.len() - 2] == '.';
                if !ends_in_dots {
                    if res.len() > 2 {
                        let cut = last_separator(&res);
                        if cut == -1 {
                            res.clear();
                            last_segment_length = 0;
                        } else {
                            res.truncate(cut as usize);
                            last_segment_length = res.len() as isize - 1 - last_separator(&res);
                        }
                        last_slash = at;
                        dots = 0;
                        continue;
                    } else if !res.is_empty() {
                        res.clear();
                        last_segment_length = 0;
                        last_slash = at;
                        dots = 0;
                        continue;
                    }
                }
                if allow_above_root {
                    if !res.is_empty() {
                        res.push(separator);
                    }
                    res.extend(['.', '.']);
                    last_segment_length = 2;
                }
            } else {
                if !res.is_empty() {
                    res.push(separator);
                }
                res.extend(&path[(last_slash + 1) as usize..i]);
                last_segment_length = at - last_slash - 1;
            }
            last_slash = at;
            dots = 0;
        } else if code == '.' && dots != -1 {
            dots += 1;
        } else {
            dots = -1;
        }
    }
    res.into_iter().collect()
}

/// `path.posix.normalize`.
fn normalize_posix(path: &str) -> String {
    if path.is_empty() {
        return ".".to_owned();
    }
    let absolute = path.starts_with('/');
    let trailing = path.ends_with('/');
    let chars: Vec<char> = path.chars().collect();
    let mut path = normalize_parts(&chars, !absolute, '/', |c| c == '/');
    if path.is_empty() {
        if absolute {
            return "/".to_owned();
        }
        return if trailing { "./" } else { "." }.to_owned();
    }
    if trailing {
        path.push('/');
    }
    if absolute { format!("/{path}") } else { path }
}

/// `path.win32.normalize`.
fn normalize_win32(path: &str) -> String {
    let sep = |c: char| c == '/' || c == '\\';
    let chars: Vec<char> = path.chars().collect();
    let len = chars.len();
    if len == 0 {
        return ".".to_owned();
    }
    if len == 1 {
        return if chars[0] == '/' {
            "\\".to_owned()
        } else {
            path.to_owned()
        };
    }
    let slice = |from: usize, to: usize| chars[from..to].iter().collect::<String>();
    let mut root_end = 0;
    let mut device: Option<String> = None;
    let mut absolute = false;
    if sep(chars[0]) {
        absolute = true;
        if sep(chars[1]) {
            let mut j = 2;
            let mut last = j;
            while j < len && !sep(chars[j]) {
                j += 1;
            }
            if j < len && j != last {
                let first = slice(last, j);
                last = j;
                while j < len && sep(chars[j]) {
                    j += 1;
                }
                if j < len && j != last {
                    last = j;
                    while j < len && !sep(chars[j]) {
                        j += 1;
                    }
                    if j == len {
                        return format!("\\\\{first}\\{}\\", slice(last, len));
                    }
                    if j != last {
                        device = Some(format!("\\\\{first}\\{}", slice(last, j)));
                        root_end = j;
                    }
                }
            }
        } else {
            root_end = 1;
        }
    } else if chars[0].is_ascii_alphabetic() && chars[1] == ':' {
        device = Some(slice(0, 2));
        root_end = 2;
        if len > 2 && sep(chars[2]) {
            absolute = true;
            root_end = 3;
        }
    }
    let mut tail = if root_end < len {
        normalize_parts(&chars[root_end..], !absolute, '\\', |c| {
            c == '/' || c == '\\'
        })
    } else {
        String::new()
    };
    if tail.is_empty() && !absolute {
        tail.push('.');
    }
    if !tail.is_empty() && sep(chars[len - 1]) {
        tail.push('\\');
    }
    match device {
        None if absolute => format!("\\{tail}"),
        None => tail,
        Some(device) if absolute => format!("{device}\\{tail}"),
        Some(device) => format!("{device}{tail}"),
    }
}

fn fold_with(normalize: fn(&str) -> String, value: &str) -> String {
    normalize(value).replace('\\', "/").to_lowercase()
}

fn within_with(normalize: fn(&str) -> String, command: &str, path: &str) -> bool {
    let root = fold_with(normalize, path);
    let root = root.trim_end_matches('/');
    let target = fold_with(normalize, command);
    target == root
        || target
            .strip_prefix(root)
            .is_some_and(|rest| rest.starts_with('/'))
}

/// `command` is `path` or lies inside it (separators and case folded: Windows).
pub fn within_path(command: &str, path: &str) -> bool {
    within_with(
        if cfg!(windows) {
            normalize_win32
        } else {
            normalize_posix
        },
        command,
        path,
    )
}

/// The wiring an earlier OMPdesk build wrote: the `ai-memory` MCP entry runs a binary OMPdesk staged or the one it
/// runs now (`owned`: the `<tools>/ai-memory` folder and the binary in use).
pub fn legacy_owned(wiring: &Wiring, owned: &[String]) -> bool {
    wiring.mcp
        && wiring
            .command
            .as_deref()
            .is_some_and(|command| owned.iter().any(|path| within_path(command, path)))
}

/// Remove the extension and the MCP entry ai-memory wrote into `agent_dir`, and nothing else: other MCP servers and
/// every other key of `mcp.json` stay (the file goes only when nothing is left in it).
pub fn remove_wiring(agent_dir: &Path) -> std::io::Result<()> {
    let extension = agent_dir.join(EXTENSION_FILE);
    if generated_extension(&extension) {
        remove_file(&extension)?;
    }
    let file = agent_dir.join(MCP_FILE);
    let Some(mut config) = read_mcp(&file) else {
        return Ok(());
    };
    let Some(Value::Object(servers)) = config.get_mut("mcpServers") else {
        return Ok(());
    };
    if !is_ai_memory_entry(servers.get(SERVER_NAME)) {
        return Ok(());
    }
    servers.shift_remove(SERVER_NAME);
    if servers.is_empty() {
        config.shift_remove("mcpServers");
    }
    if config.is_empty() {
        remove_file(&file)
    } else {
        fs::write(&file, pretty(&Value::Object(config)))
    }
}

/// `rm(file, { force: true })`.
fn remove_file(file: &Path) -> std::io::Result<()> {
    match fs::remove_file(file) {
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        done => done,
    }
}

fn names(dir: &Path) -> Option<Vec<String>> {
    Some(
        fs::read_dir(dir)
            .ok()?
            .filter_map(Result::ok)
            .map(|entry| entry.file_name().to_string_lossy().into_owned())
            .collect(),
    )
}

/// The ai-memory skills in the shared `<home>/.agents/skills` (the "before" of `remove_new_shared_skills`).
pub fn list_shared_skills(home: &Path) -> BTreeSet<String> {
    names(&home.join(".agents").join("skills"))
        .unwrap_or_default()
        .into_iter()
        .filter(|name| name.starts_with(SKILL_PREFIX))
        .collect()
}

/// `setup` writes ai-memory's managed skills to the shared `<home>/.agents/skills`, which every agent reads. When
/// OMPdesk runs `setup` only for its server, the skills it newly created there are taken back (OMPdesk loads its own
/// copy from its extension root); skills that were there before stay, and folders ai-memory created and left empty go.
pub fn remove_new_shared_skills(home: &Path, before: &BTreeSet<String>) {
    let root = home.join(".agents").join("skills");
    for name in list_shared_skills(home) {
        if before.contains(&name) {
            continue;
        }
        let skill = root.join(&name);
        if read_text(&skill.join("SKILL.md")).is_some_and(|text| text.contains("ai-memory-managed"))
        {
            let _ = fs::remove_dir_all(&skill);
        }
    }
    for folder in [root, home.join(".agents")] {
        if names(&folder).is_some_and(|names| names.is_empty()) {
            let _ = fs::remove_dir(&folder);
        }
    }
}

#[cfg(test)]
pub(super) fn within_both(command: &str, path: &str) -> (bool, bool) {
    (
        within_with(normalize_posix, command, path),
        within_with(normalize_win32, command, path),
    )
}
