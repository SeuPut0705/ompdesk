/**
 * Regenerates the lists of Rust crates statically linked into the binaries OMPdesk builds, one file per cargo
 * workspace (`WORKSPACES`): name, version, SPDX license expression, repository, and every distinct license/NOTICE
 * text those crates ship, reproduced once each.
 *
 *   bun scripts/gen-crate-notices.ts            every workspace
 *   bun scripts/gen-crate-notices.ts ompdesk    one (`ai-memory`, `ompdesk`)
 *
 * Needs `cargo` and network access (crate sources). Run it whenever a workspace's Cargo.lock changes, then run
 * `bun run gen:licenses` and commit both outputs. The committed files are what the app ships;
 * `bun run licenses:check` (scripts/generate-third-party-notices.ts) fails when a file's Cargo.lock SHA-256 differs
 * from its workspace's Cargo.lock.
 *
 * Method: `cargo metadata --locked` for each release target (aarch64-apple-darwin, x86_64-pc-windows-msvc) from the
 * crates OMPdesk builds. The set is the union of both targets' graphs, following normal dependency edges only:
 * build-only and dev dependencies are not linked and are skipped, as are proc-macro crates (they run at compile
 * time). A workspace's own crates are covered by the workspace's license. Texts are read from the downloaded crate
 * sources, so they are exactly what each crate ships.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { cargoPath } from "./cargo";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const TARGETS = ["aarch64-apple-darwin", "x86_64-pc-windows-msvc"];
const LICENSE_FILE = /^(licen[sc]e|copying|notice|unlicense)(\.|-|_|$)/i;
const RULE = "=".repeat(78);
const THIN = "-".repeat(78);

interface MetaPackage {
	id: string;
	name: string;
	version: string;
	license: string | null;
	license_file: string | null;
	repository: string | null;
	manifest_path: string;
	source: string | null;
	targets: { kind: string[] }[];
}

interface MetaNode {
	id: string;
	deps: { pkg: string; dep_kinds: { kind: string | null }[] }[];
}

interface Metadata {
	packages: MetaPackage[];
	resolve: { nodes: MetaNode[] };
	workspace_members: string[];
}

interface Crate {
	name: string;
	version: string;
	license: string;
	repository: string;
	texts: string[];
}

export interface Workspace {
	/** Folder of the cargo workspace, relative to the repository. */
	dir: string;
	/** The committed list, relative to the repository. */
	output: string;
	/** The manifest `cargo metadata` reads, relative to `dir`; absent: the workspace's own. */
	manifest?: string;
	/** The crates OMPdesk builds; absent: every member of the workspace. */
	roots?: string[];
	/** The file's first line. */
	title(): string;
	/** The paragraph under the Cargo.lock hash. */
	intro(): string[];
}

const aiMemoryVersion = (): string =>
	(JSON.parse(readFileSync(join(ROOT, "native", "memory", "ompdesk.json"), "utf8")) as { version: string }).version;

export const WORKSPACES = {
	"ai-memory": {
		dir: "native/memory",
		output: "LICENSES/ai-memory-dependencies.txt",
		manifest: "crates/ai-memory-cli/Cargo.toml",
		roots: ["ai-memory-cli"],
		title: () => `ai-memory ${aiMemoryVersion()} statically linked Rust crates`,
		intro: () => [
			`The ai-memory ${aiMemoryVersion()} binary OMPdesk builds from native/memory (https://github.com/akitaonrails/ai-memory)`,
			"links the crates below. Set: normal dependencies of `ai-memory-cli` for aarch64-apple-darwin and",
			"x86_64-pc-windows-msvc, per native/memory/Cargo.lock; build-only and proc-macro crates are not linked. ai-memory's",
			"own workspace crates are under ai-memory's license (LICENSES/ai-memory-LICENSE). Generated by",
			"scripts/gen-crate-notices.ts; do not edit by hand.",
		],
	},
	ompdesk: {
		dir: "native/ompdesk",
		output: "LICENSES/ompdesk-native-dependencies.txt",
		title: () => "OMPdesk native binaries: statically linked Rust crates",
		intro: () => [
			"The binaries OMPdesk builds from its own Rust source in native/ompdesk (shipped under ompdesk-bin/) link the",
			"crates below. Set: normal dependencies of every workspace crate for aarch64-apple-darwin and",
			"x86_64-pc-windows-msvc, per native/ompdesk/Cargo.lock; build-only and proc-macro crates are not linked. The",
			"workspace's own crates are OMPdesk's, under the Apache License, Version 2.0 (LICENSE). Generated by",
			"scripts/gen-crate-notices.ts; do not edit by hand.",
		],
	},
} satisfies Record<string, Workspace>;

export type WorkspaceName = keyof typeof WORKSPACES;

/** SHA-256 of a workspace's Cargo.lock with line endings normalized: what its committed crate list is made for. */
export function lockHash(workspace: Workspace): string {
	return createHash("sha256")
		.update(readFileSync(join(ROOT, workspace.dir, "Cargo.lock"), "utf8").replace(/\r\n?/g, "\n"))
		.digest("hex");
}

/**
 * The committed crate list of `name`; throws when it was made for another title (a version it names) or another
 * Cargo.lock.
 */
export function committedCrateList(name: WorkspaceName): string {
	const workspace: Workspace = WORKSPACES[name];
	const text = readFileSync(join(ROOT, workspace.output), "utf8").replace(/\r\n?/g, "\n").trim();
	if (!text.startsWith(workspace.title()) || !text.includes(`Cargo.lock SHA-256: ${lockHash(workspace)}`)) {
		throw new Error(
			`${workspace.output} is not for ${workspace.dir} with its current Cargo.lock: run bun scripts/gen-crate-notices.ts ${name} (needs cargo and network).`,
		);
	}
	return text;
}

function run(cmd: string, args: string[], cwd?: string): string {
	return execFileSync(cmd, args, {
		cwd,
		encoding: "utf8",
		maxBuffer: 256 * 1024 * 1024,
		stdio: ["ignore", "pipe", "inherit"],
	});
}

const normalize = (text: string): string => text.replace(/\r\n?/g, "\n").trim();

function linked(meta: Metadata, workspace: Workspace): Map<string, MetaPackage> {
	const byId = new Map(meta.packages.map(pkg => [pkg.id, pkg]));
	const nodes = new Map(meta.resolve.nodes.map(node => [node.id, node]));
	const stack = workspace.roots
		? workspace.roots.map(root => {
				const start = meta.packages.find(pkg => pkg.name === root && pkg.source === null);
				if (!start) throw new Error(`${workspace.dir}: ${root} not found`);
				return start.id;
			})
		: [...meta.workspace_members];
	const seen = new Map<string, MetaPackage>();
	while (stack.length) {
		const id = stack.pop() as string;
		if (seen.has(id)) continue;
		const pkg = byId.get(id);
		if (!pkg) continue;
		seen.set(id, pkg);
		for (const dep of nodes.get(id)?.deps ?? []) {
			if (dep.dep_kinds.some(kind => kind.kind === null)) stack.push(dep.pkg);
		}
	}
	return seen;
}

function texts(pkg: MetaPackage): string[] {
	const dir = dirname(pkg.manifest_path);
	const files = readdirSync(dir)
		.filter(name => LICENSE_FILE.test(name))
		.sort();
	if (pkg.license_file && !files.includes(pkg.license_file) && existsSync(join(dir, pkg.license_file))) {
		files.push(pkg.license_file);
	}
	return files.map(name => normalize(readFileSync(join(dir, name), "utf8"))).filter(text => text.length > 0);
}

function generate(workspace: Workspace, cargo: string): void {
	const crates = new Map<string, Crate>();
	const members = new Set<string>();
	for (const target of TARGETS) {
		const meta = JSON.parse(
			run(
				cargo,
				[
					"metadata",
					"--locked",
					"--format-version",
					"1",
					"--filter-platform",
					target,
					...(workspace.manifest ? ["--manifest-path", workspace.manifest] : []),
				],
				join(ROOT, workspace.dir),
			),
		) as Metadata;
		for (const pkg of linked(meta, workspace).values()) {
			if (pkg.source === null) {
				members.add(pkg.name);
				continue;
			}
			if (pkg.targets.some(t => t.kind.includes("proc-macro"))) continue;
			const key = `${pkg.name}@${pkg.version}`;
			if (crates.has(key)) continue;
			crates.set(key, {
				name: pkg.name,
				version: pkg.version,
				license: pkg.license ?? "UNKNOWN",
				repository: pkg.repository ?? "(none declared)",
				texts: texts(pkg),
			});
		}
	}

	const list = [...crates.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
	const textIds = new Map<string, number>();
	for (const crate of list) {
		for (const text of crate.texts) if (!textIds.has(text)) textIds.set(text, textIds.size + 1);
	}
	const flagged = list.filter(crate => crate.texts.length === 0);
	for (const crate of flagged)
		console.warn(`no license file shipped: ${crate.name}@${crate.version} (${crate.license})`);

	const out: string[] = [
		workspace.title(),
		"",
		`Cargo.lock SHA-256: ${lockHash(workspace)}`,
		"",
		...workspace.intro(),
		"",
		`${list.length} crates, ${textIds.size} distinct license/notice texts.`,
		"",
		RULE,
		"Crates: name version (SPDX license expression) repository [license text numbers below]",
		RULE,
		"",
	];
	for (const crate of list) {
		const refs = crate.texts.map(text => textIds.get(text)).join(",");
		out.push(`${crate.name} ${crate.version} (${crate.license}) ${crate.repository} [${refs || "none shipped"}]`);
	}
	out.push("", RULE, "License and notice texts", RULE, "");
	for (const [text, id] of textIds) out.push(`[${id}]`, "", text, "", THIN, "");
	if (flagged.length) {
		out.push(
			"Crates whose published package ships no license file",
			"",
			"The following crates declare the license shown in their Cargo.toml but their package carries no",
			"license text. The standard text of that license applies (Apache-2.0: LICENSES/Apache-2.0.txt",
			"beside THIRD_PARTY_NOTICES.txt; MIT: the MIT text in this file), with the copyright of the crate's",
			"authors as stated in the repository listed above.",
			"",
			...flagged.map(crate => `- ${crate.name} ${crate.version} (${crate.license}) ${crate.repository}`),
			"",
		);
	}
	const output = join(ROOT, workspace.output);
	writeFileSync(
		output,
		`${out
			.join("\n")
			.replace(/\n{4,}/g, "\n\n\n")
			.trimEnd()}\n`,
	);
	console.log(
		`Wrote ${output}: ${list.length} crates, ${textIds.size} texts, ${flagged.length} without license file.`,
	);
	console.log(`Workspace crates skipped: ${[...members].sort().join(", ")}`);
}

if (import.meta.main) {
	const cargo = cargoPath();
	if (!cargo) {
		console.error("gen-crate-notices: Rust is not installed (no `cargo` on PATH or in ~/.cargo/bin).");
		process.exit(1);
	}
	const asked = process.argv.slice(2);
	const names = asked.length ? asked : Object.keys(WORKSPACES);
	for (const name of names) {
		if (!(name in WORKSPACES)) {
			console.error(`gen-crate-notices: no workspace "${name}" (${Object.keys(WORKSPACES).join(", ")}).`);
			process.exit(1);
		}
		generate(WORKSPACES[name as WorkspaceName], cargo);
	}
}
