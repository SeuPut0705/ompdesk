import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import * as fs from "node:fs";
import * as path from "node:path";
import { fileURLToPath } from "node:url";
import { cargoEnv, cargoPath, rustcPath } from "./cargo";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workspace = path.join(root, "native", "ompdesk");
export const MEMORY_POLICY_SOURCE = path.join(root, "resources", "gui-bridge", "memory-policy-wasm.ts");
export const MEMORY_POLICY_INPUTS = [
	"native/ompdesk/crates/core/src/aimemory/prompt_policy.rs",
	"native/ompdesk/crates/memory-policy/Cargo.toml",
	"native/ompdesk/crates/memory-policy/src/lib.rs",
	"native/ompdesk/crates/memory-policy/src/sys.rs",
	"native/ompdesk/rust-toolchain.toml",
	"native/ompdesk/Cargo.lock",
	"scripts/cargo.ts",
	"scripts/build-memory-policy.ts",
	"resources/gui-bridge/memory-policy.ts",
	"resources/gui-bridge/memory-prompt.ts",
	"resources/gui-bridge/redactor.ts",
];

function inputHash(): string {
	const hash = createHash("sha256");
	for (const file of MEMORY_POLICY_INPUTS)
		hash
			.update(file)
			.update("\0")
			.update(fs.readFileSync(path.join(root, file)));
	return hash.digest("hex");
}

export function buildMemoryPolicy(check = false): void {
	const inputs = inputHash();
	if (check) {
		const source = fs.readFileSync(MEMORY_POLICY_SOURCE, "utf8");
		if (!source.includes(`// inputs-sha256: ${inputs}\n`))
			throw new Error("Embedded memory policy is stale; run bun scripts/build-memory-policy.ts.");
		const encoded = source.match(/export const MEMORY_POLICY_WASM_BASE64\s*=\s*"([A-Za-z0-9+/=]+)";/);
		if (!encoded) throw new Error("Embedded memory policy bytes are missing.");
		const artifact = Buffer.from(encoded[1], "base64");
		const digest = createHash("sha256").update(artifact).digest("hex");
		if (!source.includes(`// wasm-sha256: ${digest}\n`))
			throw new Error("Embedded memory policy bytes differ from their build record.");
		const instance = new WebAssembly.Instance(new WebAssembly.Module(artifact));
		const abi = instance.exports.policy_abi_version;
		if (typeof abi !== "function" || abi() !== 1) throw new Error("Embedded memory policy ABI is not supported.");
		return;
	}
	const cargo = cargoPath(workspace);
	if (!cargo) throw new Error("Rust is required to build the embedded memory policy.");
	const env = { ...cargoEnv(cargo), RUSTC: rustcPath(cargo) };
	const result = spawnSync(
		cargo,
		["build", "--locked", "--release", "--target", "wasm32-unknown-unknown", "-p", "ompdesk-memory-policy"],
		{ cwd: workspace, env, stdio: "inherit" },
	);
	if (result.status !== 0) throw new Error(`Memory policy build failed (${result.status ?? result.signal}).`);
	const target = env.CARGO_TARGET_DIR ? path.resolve(workspace, env.CARGO_TARGET_DIR) : path.join(workspace, "target");
	const artifact = fs.readFileSync(
		path.join(target, "wasm32-unknown-unknown", "release", "ompdesk_memory_policy.wasm"),
	);
	const digest = createHash("sha256").update(artifact).digest("hex");
	const source = `// Generated by scripts/build-memory-policy.ts from the canonical Rust policy.\n// inputs-sha256: ${inputs}\n// wasm-sha256: ${digest}\nexport const MEMORY_POLICY_WASM_BASE64 =\n\t"${artifact.toString("base64")}";\n`;
	if (!fs.existsSync(MEMORY_POLICY_SOURCE) || fs.readFileSync(MEMORY_POLICY_SOURCE, "utf8") !== source) {
		fs.writeFileSync(MEMORY_POLICY_SOURCE, source);
	}
}

if (import.meta.main) buildMemoryPolicy(process.argv.includes("--check"));
