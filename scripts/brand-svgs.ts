/**
 * Every brand SVG in resources/, built from the π geometry in
 * src/shared/brand-mark.ts. `bun run gen:icons` writes these files (then
 * rasterizes them); brand-mark.test.ts fails when a checked-in file differs.
 */
import { BRAND_MARK, type PiGeometry } from "../src/shared/brand-mark";

interface Paint {
	ink: string;
	accent: string;
}

const LIGHT: Paint = { ink: "#17171C", accent: "#5B5BD6" };
const DARK: Paint = { ink: "#F4F4F6", accent: "#8B8DF8" };
const TILE: Paint = { ink: "url(#pi-ink)", accent: "url(#pi-accent)" };
const MONO: Paint = { ink: "#000000", accent: "#000000" };

const { tile } = BRAND_MARK;
const gradient = (id: string, stops: typeof tile.ink | typeof tile.accent) =>
	`<linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="${tile.from[0]}" y1="${tile.from[1]}" x2="${tile.to[0]}" y2="${tile.to[1]}">${stops.map(([offset, color]) => `<stop offset="${offset}" stop-color="${color}"/>`).join("")}</linearGradient>`;
const TILE_DEFS = `  <defs>${gradient("pi-ink", tile.ink)}${gradient("pi-accent", tile.accent)}</defs>\n`;

/** The π centred at the origin: ink first, the accent foot over it. */
const pi = (g: PiGeometry, p: Paint) =>
	`  <path d="${g.ink}" fill="${p.ink}"/>\n  <path d="${g.accent}" fill="${p.accent}"/>\n`;

const svg = (viewBox: string, comment: string, body: string) =>
	`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="none">\n  <!-- ${comment}\n       Generated by scripts/gen-icons.ts from src/shared/brand-mark.ts; do not edit. -->\n${body}</svg>\n`;

const mark = (g: PiGeometry, p: Paint, comment: string) => svg(BRAND_MARK.viewBox, comment, pi(g, p));

/** Full-bleed tile body: the π in platinum with an indigo foot on the ink tile. */
const tileBody = (g: PiGeometry) =>
	`${TILE_DEFS}  <rect x="-256" y="-256" width="512" height="512" rx="${tile.radius}" fill="${tile.background}"/>\n  <g transform="scale(${tile.glyphScale})">\n${pi(g, TILE)}  </g>\n`;

const tileSvg = (g: PiGeometry, comment: string) => svg(BRAND_MARK.viewBox, comment, tileBody(g));

/**
 * The renderer's favicon (src/renderer/index.html `<link rel="icon">`): the
 * pixel-grid tile as a data URL, which gen-icons writes into the page.
 */
export const FAVICON_HREF = `data:image/svg+xml,${`<svg xmlns='http://www.w3.org/2000/svg' viewBox='${BRAND_MARK.viewBox}' fill='none'>${tileBody(BRAND_MARK.small).trim()}</svg>`
	.replace(/\n\s*/g, "")
	.replaceAll('"', "'")
	.replace(/[<>#%]/g, encodeURIComponent)}`;

/**
 * macOS app icon on Apple's 1024 grid: 824 tile inset 100 (~22.5% corners) with
 * a hairline edge, the π at the tile's glyph scale.
 */
const appIcon = (g: PiGeometry, comment: string) => {
	const scale = (824 / 512) * tile.glyphScale;
	return svg(
		"0 0 1024 1024",
		comment,
		`${TILE_DEFS}  <rect x="100" y="100" width="824" height="824" rx="185" fill="${tile.background}"/>\n  <rect x="101.5" y="101.5" width="821" height="821" rx="183.5" stroke="#FFFFFF" stroke-opacity="0.08" stroke-width="3"/>\n  <g transform="translate(512 512) scale(${Math.round(scale * 10000) / 10000})">\n${pi(g, TILE)}  </g>\n`,
	);
};

/**
 * Monoline wordmark letters (stroke 3.2, bowl r 8.4, x-height 11.6–28.4, 6.6
 * between letters): o m p d e s k. The m arches are r 5.6; the p descender
 * stops at 34.4 so its cap meets the frame.
 */
const WORDMARK_LETTERS = [
	`<circle cx="10" cy="20" r="8.4"/>`,
	`<path d="M25 11.6V28.4M25 17.2A5.6 5.6 0 0 1 36.2 17.2V28.4M36.2 17.2A5.6 5.6 0 0 1 47.4 17.2V28.4"/>`,
	`<path d="M54 11.6V34.4"/>`,
	`<circle cx="62.4" cy="20" r="8.4"/>`,
	`<circle cx="85.8" cy="20" r="8.4"/>`,
	`<path d="M94.2 3.6V28.4"/>`,
	`<path d="M100.8 20H117.6A8.4 8.4 0 1 0 115.63 25.4"/>`,
	`<path d="M132.11 13.83A4.2 4.2 0 1 0 128.4 20A4.2 4.2 0 1 1 124.69 26.17"/>`,
	`<path d="M139.2 3.6V28.4M149.2 11.6L139.2 21.6M142.8 18L149.6 28.4"/>`,
];
/**
 * Lockup: the letters sit at translate(43 4), so their ascenders (d, k) reach
 * y 6 and the baseline caps y 34 once the round caps are counted. The full π is
 * scaled to that same 28-unit span (bar top on the ascender, right leg on the
 * baseline), 32 units wide from x 1, with a 10-unit gap before the "o".
 */
const WORDMARK_SCALE = 28 / 392;
const wordmark = (p: Paint, background: string) =>
	svg(
		"0 0 196 40",
		`ompdesk lockup for ${background} backgrounds: the full π (bar on the ascender line, right leg on the baseline) and a monoline geometric wordmark.`,
		`  <g transform="translate(17 20) scale(${Math.round(WORDMARK_SCALE * 100000) / 100000})">\n${pi(BRAND_MARK.full, p)}  </g>\n  <g transform="translate(43 4)" stroke="${p.ink}" stroke-width="3.2" stroke-linecap="round" stroke-linejoin="round">\n${WORDMARK_LETTERS.map(l => `    ${l}\n`).join("")}  </g>\n`,
	);

