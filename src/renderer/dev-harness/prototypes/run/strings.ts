const DICTS: Record<"en" | "ko", Dict> = { en, ko };

export function protoText(lang: string, key: string, params?: Record<string, string | number>): string {
	const dict = lang === "ko" ? DICTS.ko : DICTS.en;
	const raw = dict[key] ?? en[key] ?? key;
	if (!params) return raw;
	return raw.replace(/\{(\w+)\}/g, (match, name: string) =>
		Object.hasOwn(params, name) ? String(params[name]) : match,
	);
}

export type PT = (key: string, params?: Record<string, string | number>) => string;

/** `p("proto key")` for the new wording; `useT()` stays the way to read a real locale key. */
export function useP(): PT {
	const { lang } = useLang();
	return useCallback((key, params) => protoText(lang, key, params), [lang]);
}

export { useT };
