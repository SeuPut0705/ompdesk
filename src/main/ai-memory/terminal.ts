/**
 * ai-memory's wiring of the plain terminal `omp`: what `ai-memory setup --agent omp` writes into omp's agent dir.
 *
 * OMPdesk never writes it by itself. It exists when the user pressed "Also use in the terminal omp" (OMPdesk then runs
 * ai-memory's own `setup --agent omp`), when the user ran ai-memory's setup in a terminal, or when an earlier OMPdesk
 * build wired omp globally (`legacyOwned`). The reverse removes exactly the two things ai-memory adds there and nothing
 * else: ai-memory has no per-agent uninstall (`uninstall` removes every agent's wiring it finds), so this reads them back
 * by their own signatures (the generated file's header, the `ai-memory` MCP entry running an ai-memory binary).
 * The skills `setup` also writes go to the shared `~/.agents/skills` and belong to every agent reading it, so they stay.
 */
import { readdir, readFile, rm, rmdir, writeFile } from "node:fs/promises";
import { basename, join, normalize } from "node:path";

/** The files ai-memory's omp installer writes under omp's agent dir. */
export const EXTENSION_FILE = join("extensions", "ai-memory-omp.ts");
export const MCP_FILE = "mcp.json";
/** The first line of every extension `install-hooks --agent omp` generates. */
export const GENERATED_HEADER = "// Auto-generated by `ai-memory install-hooks --agent omp";
const SERVER_NAME = "ai-memory";

export interface TerminalWiring {
	extension: boolean;
	mcp: boolean;
	/** The MCP entry's command (null without an entry). */
	command: string | null;
}

interface McpFile {
	mcpServers?: Record<string, unknown>;
	[key: string]: unknown;
}

export async function readMcp(file: string): Promise<McpFile | null> {
	try {
		const parsed: unknown = JSON.parse(await readFile(file, "utf8"));
		return parsed !== null && typeof parsed === "object" && !Array.isArray(parsed) ? (parsed as McpFile) : null;
	} catch {
		return null;
	}
}

/** Whether `entry` is the stdio or http server ai-memory's `install-mcp` writes. */
function isAiMemoryEntry(entry: unknown): entry is { command?: unknown; url?: unknown } {
	if (entry === null || typeof entry !== "object") return false;
	const { command, url } = entry as { command?: unknown; url?: unknown };
	if (typeof command === "string") return /^ai-memory(\.exe|\.cmd)?$/i.test(basename(command.replaceAll("\\", "/")));
	return typeof url === "string" && /\/mcp\/?$/.test(url);
}

async function generatedExtension(file: string): Promise<boolean> {
	const text = await readFile(file, "utf8").catch(() => null);
	return text !== null && text.startsWith(GENERATED_HEADER);
}

export async function readTerminalWiring(agentDir: string): Promise<TerminalWiring> {
	const extension = await generatedExtension(join(agentDir, EXTENSION_FILE));
	const entry = (await readMcp(join(agentDir, MCP_FILE)))?.mcpServers?.[SERVER_NAME];
	const mcp = isAiMemoryEntry(entry);
	return { extension, mcp, command: mcp && typeof entry.command === "string" ? entry.command : null };
}

/** `command` is `path` or lies inside it (separators and case folded: Windows). */
export function withinPath(command: string, path: string): boolean {
	const fold = (value: string) => normalize(value).replaceAll("\\", "/").toLowerCase();
	const root = fold(path).replace(/\/+$/, "");
	const target = fold(command);
	return target === root || target.startsWith(`${root}/`);
}

/**
 * The wiring an earlier OMPdesk build wrote: the `ai-memory` MCP entry runs a binary OMPdesk staged or the one it
 * runs now (`owned`: the `<tools>/ai-memory` folder and the binary in use).
 */
export function legacyOwned(wiring: TerminalWiring, owned: string[]): boolean {
	const { command } = wiring;
	return wiring.mcp && command !== null && owned.some(path => withinPath(command, path));
}

/**
 * Remove the extension and the MCP entry ai-memory wrote into `agentDir`, and nothing else: other MCP servers and
 * every other key of `mcp.json` stay (the file goes only when nothing is left in it).
 */
export async function removeTerminalWiring(agentDir: string): Promise<void> {
	const extension = join(agentDir, EXTENSION_FILE);
	if (await generatedExtension(extension)) await rm(extension, { force: true });
	const file = join(agentDir, MCP_FILE);
	const config = await readMcp(file);
	if (!config?.mcpServers || !isAiMemoryEntry(config.mcpServers[SERVER_NAME])) return;
	delete config.mcpServers[SERVER_NAME];
	if (Object.keys(config.mcpServers).length === 0) delete config.mcpServers;
	if (Object.keys(config).length === 0) await rm(file, { force: true });
	else await writeFile(file, `${JSON.stringify(config, null, 2)}\n`);
}

/** Folder names below `<home>/.agents/skills` that ai-memory manages start with this. */
const SKILL_PREFIX = "ai-memory-";

/**
 * `setup` writes ai-memory's managed skills to the shared `<home>/.agents/skills`, which every agent reads. When OMPdesk
 * runs `setup` only for its server, the skills it newly created there are taken back (OMPdesk loads its own copy from
 * its extension root); skills that were there before stay. `listSharedSkills` is the "before".
 */
export async function listSharedSkills(home: string): Promise<Set<string>> {
	const names = await readdir(join(home, ".agents", "skills")).catch(() => [] as string[]);
	return new Set(names.filter(name => name.startsWith(SKILL_PREFIX)));
}

export async function removeNewSharedSkills(home: string, before: Set<string>): Promise<void> {
	const root = join(home, ".agents", "skills");
	for (const name of await listSharedSkills(home)) {
		if (before.has(name)) continue;
		const skill = join(root, name);
		const text = await readFile(join(skill, "SKILL.md"), "utf8").catch(() => null);
		if (text?.includes("ai-memory-managed")) await rm(skill, { recursive: true, force: true });
	}
	// Folders ai-memory created and left empty go too (never one with anything in it).
	for (const folder of [root, join(home, ".agents")]) {
		if ((await readdir(folder).catch(() => ["x"])).length === 0) await rmdir(folder).catch(() => undefined);
	}
}
