import { execFileSync, spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import * as fs from "node:fs/promises";
import * as net from "node:net";
import * as os from "node:os";
import * as path from "node:path";
import { expect, type Page, test } from "@playwright/test";
import type { ElectronApplication } from "playwright";
import { exitApp, launchApp } from "./harness";

// The REAL ai-memory.exe (`bun run sync:ai-memory`) with its real Windows logon entry, on a real Windows (CI's
// `win-e2e` job sets OMP_GUI_REAL_AI_MEMORY_SERVICE=1; a developer's machine never runs it by accident): memory sets
// itself up through ai-memory's own `setup` (the HKCU `Run` entry, the hidden `service-host` supervisor, the server),
// OMPdesk's own extension root is generated by ai-memory's generators, nothing is written to omp's agent dir, the
// terminal button runs the real `setup --agent omp` and removes only that, and turning memory off removes the logon
// entry, ends the supervisor and the server and leaves the .exe unlocked (a running server holds its image open, which
// is why OMPdesk never runs the shipped file in place). The fake omp stands in for omp: no model is involved.
//
// Isolation: AI_MEMORY_DATA_DIR points into the test's own folder (ai-memory resolves the profile through Windows'
// known folders, which HOME/USERPROFILE do not move; the runner is thrown away). The logon entry is the one thing global to the
// user; the spec only runs while that value and port 49374 are free, and removes them again at the end.
const PORT = 49374;
const RUN_KEY = String.raw`HKCU\Software\Microsoft\Windows\CurrentVersion\Run`;

function realExe(): string | null {
	const file = path.resolve("resources/ai-memory-bin/win32-x64/ai-memory.exe");
	return existsSync(file) ? file : null;
}

/** The `ai-memory` logon entry's command line, or null when there is none. */
function logonEntry(): string | null {
	const result = spawnSync("reg", ["query", RUN_KEY, "/v", "ai-memory"], { encoding: "utf8" });
	if (result.status !== 0) return null;
	return /ai-memory\s+REG_(?:EXPAND_)?SZ\s+(.+)/i.exec(result.stdout)?.[1]?.trim() ?? null;
}

async function portBusy(): Promise<boolean> {
	const { promise, resolve } = Promise.withResolvers<boolean>();
	const socket = net.connect(PORT, "127.0.0.1");
	socket.once("connect", () => {
		socket.destroy();
		resolve(true);
	});
	socket.once("error", () => resolve(false));
	return promise;
}

async function healthy(): Promise<boolean> {
	return fetch(`http://127.0.0.1:${PORT}/healthz`, { signal: AbortSignal.timeout(2_000) }).then(
		response => response.ok,
		() => false,
	);
}

function alive(pid: number): boolean {
	const result = spawnSync("tasklist", ["/FI", `PID eq ${pid}`, "/NH"], { encoding: "utf8" });
	return result.stdout.includes(String(pid));
}

test("real ai-memory.exe on Windows: the logon entry follows the switch, only OMPdesk's part is touched, the .exe is not left locked", async () => {
	test.skip(process.platform !== "win32", "Windows-only: it drives the HKCU Run logon entry");
	test.skip(
		process.env.OMP_GUI_REAL_AI_MEMORY_SERVICE !== "1",
		"Set OMP_GUI_REAL_AI_MEMORY_SERVICE=1 (CI's win-e2e does)",
	);
	const shipped = realExe();
	test.skip(!shipped, "No real ai-memory.exe: run `bun run sync:ai-memory`");
	test.skip(logonEntry() !== null, "an ai-memory logon entry already exists: not touching it");
	test.skip(await portBusy(), `port ${PORT} is already in use: not touching it`);
	if (!shipped) return;
	test.setTimeout(420_000);

	const root = await fs.realpath(await fs.mkdtemp(path.join(os.tmpdir(), "omp-real-ai-memory-")));
	const [home, desktop, agent, project, binDir, dataDir] = ["home", "desktop", "agent", "project", "bin", "data"].map(
		name => path.join(root, name),
	);
	await Promise.all([home, desktop, agent, project, binDir].map(dir => fs.mkdir(dir, { recursive: true })));
	await fs.writeFile(
		path.join(desktop, "prefs.json"),
		JSON.stringify({ firstRunComplete: true, language: "en", themeName: "light" }),
	);
	// A copy of the release binary: the spec moves it at the end to prove nothing still holds it open.
	const bin = path.join(binDir, "ai-memory.exe");
	await fs.copyFile(shipped, bin);
	// Only the data is isolated: ai-memory finds the profile through Windows' known folders, so moving HOME/USERPROFILE or
	// setting AI_MEMORY_HOME would make OMPdesk and ai-memory disagree about where `~` is (and breaks ai-memory's uninstall).
	const isolation = { AI_MEMORY_DATA_DIR: dataDir };
	const cleanup = () =>
		spawnSync(bin, ["uninstall", "--apply", "--yes"], {
			env: { ...process.env, ...isolation, PI_CODING_AGENT_DIR: agent },
			encoding: "utf8",
			timeout: 120_000,
		});

	let app: ElectronApplication | null = null;
	try {
		app = await launchApp({
			project,
			desktop,
			agent,
			profile: root,
			env: { ...isolation, OMP_GUI_AI_MEMORY_BIN: bin, PI_CONFIG_DIR: "omp-config" },
		});
		const page: Page = await app.firstWindow();
		await page.waitForFunction(() => window.omp?.rpc != null);
		const state = () => page.evaluate(() => window.omp.aiMemory.getState());
		const phase = async (wanted: string) => {
			try {
				await expect.poll(async () => (await state()).phase, { timeout: 240_000 }).toBe(wanted);
			} catch (error) {
				throw new Error(`ai-memory never reached ${wanted}: ${JSON.stringify(await state())}`, { cause: error });
			}
		};

		await phase("ready");
		const extRoot = path.join(desktop, "ai-memory", "omp-ext");
		expect(await state()).toMatchObject({ enabled: true, binary: bin, wiring: { app: true, terminal: false } });
		// ai-memory's own generators filled OMPdesk's root; omp's agent dir and the shared skills folder stay empty.
		expect(existsSync(path.join(extRoot, "index.ts"))).toBe(true);
		expect(existsSync(path.join(extRoot, ".mcp.json"))).toBe(true);
		expect((await fs.readdir(path.join(extRoot, "skills"))).length).toBeGreaterThan(0);
		expect(
			await fs.readdir(agent).then(names => names.filter(name => /ai-memory|mcp\.json|extensions/.test(name))),
		).toEqual([]);
		// ai-memory resolves its profile through the known folders, so the shared skills folder is the runner's real one.
		expect(existsSync(path.join(os.homedir(), ".agents", "skills", "ai-memory-retrieval"))).toBe(false);
		// The logon entry is ai-memory's own and runs the binary OMPdesk runs; the server answers.
		const entry = logonEntry();
		expect(entry?.toLowerCase()).toContain(bin.toLowerCase());
		expect(await healthy()).toBe(true);
		const host = JSON.parse(await fs.readFile(path.join(dataDir, "service-host.json"), "utf8")) as {
			supervisor_pid?: number;
			server_pid?: number;
		};
		const pids = [host.supervisor_pid, host.server_pid].filter((pid): pid is number => typeof pid === "number");
		expect(pids.length).toBeGreaterThan(0);
		for (const pid of pids) expect(alive(pid)).toBe(true);

		// The terminal button: ai-memory's real `setup --agent omp` into the agent dir, and only that comes out again.
		await page.evaluate(() => window.omp.aiMemory.setTerminal(true));
		expect(existsSync(path.join(agent, "extensions", "ai-memory-omp.ts"))).toBe(true);
		expect(Object.keys(JSON.parse(await fs.readFile(path.join(agent, "mcp.json"), "utf8")).mcpServers)).toEqual([
			"ai-memory",
		]);
		expect(await state()).toMatchObject({ wiring: { app: true, terminal: true } });
		await page.evaluate(() => window.omp.aiMemory.setTerminal(false));
		expect(existsSync(path.join(agent, "extensions", "ai-memory-omp.ts"))).toBe(false);
		expect(existsSync(path.join(agent, "mcp.json"))).toBe(false);
		expect(await state()).toMatchObject({ wiring: { app: true, terminal: false } });

		// Off: OMPdesk started the service and nothing else uses it, so the entry, the supervisor and the server go.
		await page.evaluate(() => window.omp.aiMemory.setEnabled(false));
		await phase("off");
		const listing = spawnSync(bin, ["uninstall"], {
			env: { ...process.env, ...isolation, PI_CODING_AGENT_DIR: agent },
			encoding: "utf8",
		});
		expect(
			logonEntry(),
			`the logon entry survived "off"; ai-memory's uninstall dry run says:\n${listing.stdout}${listing.stderr}\nstate: ${JSON.stringify(await state())}`,
		).toBeNull();
		await expect.poll(healthy, { timeout: 30_000 }).toBe(false);
		for (const pid of pids) await expect.poll(() => alive(pid), { timeout: 30_000 }).toBe(false);
		expect(existsSync(extRoot)).toBe(false);
		expect(existsSync(path.join(dataDir, "config.toml"))).toBe(true);
		// Nothing holds the binary open any more.
		await expect
			.poll(
				async () =>
					fs.rename(bin, `${bin}.moved`).then(
						() => true,
						() => false,
					),
				{ timeout: 30_000 },
			)
			.toBe(true);
	} finally {
		if (app) await exitApp(app);
		await fs.rename(`${bin}.moved`, bin).catch(() => undefined);
		cleanup();
		if (logonEntry() !== null) execFileSync("reg", ["delete", RUN_KEY, "/v", "ai-memory", "/f"]);
		// Best effort: ai-memory's service host was started with this folder as its working directory, which Windows
		// will not delete while it is open; the runner is thrown away anyway, and a failure here must not hide the result.
		await fs.rm(root, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 }).catch(() => undefined);
	}
});
